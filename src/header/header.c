void h_printf (CHeader *h, const char *fmt, ...)
{
	va_list ap;
	va_list probe;

	va_start(ap, fmt);
	va_copy(probe, ap);
	int need = vsnprintf(NULL, 0, fmt, probe);
	va_end(probe);
	if (need < 0) {
		va_end(ap);
		return;
	}
	if (h->len + (size_t)need + 1 > h->cap) {
		size_t cap = h->cap;

		while (h->len + (size_t)need + 1 > cap) cap <<= 1;
		char *code = realloc(h->code, cap);

		if (!code) {
			fprintf(stderr, "Not enough memory\n");
			exit(1);
		}
		h->code = code;
		h->cap = cap;
	}
	vsnprintf(h->code + h->len, (size_t)need + 1, fmt, ap);
	va_end(ap);
	h->len += (size_t)need;
}

void h_indent (CHeader *h, int depth)
{
	for (int i = 0; i < depth; i++)
		h_printf(h, "\t");
}

static int has_exports (Sema *sema)
{
	AST *ast = sema->ast;

	for (uint32_t idx = ast->nodes[0].child; idx != NO_NODE;
			idx = ast->nodes[idx].next_bro) {
		uint16_t flags = ast->nodes[idx].flags;

		if ((flags & NODE_FLAG_EXPORT) && !(flags & NODE_FLAG_IMPORTED))
			return 1;
	}
	return 0;
}

static void make_guard (CHeader *h)
{
	const char *mod = h->ir->mod;
	size_t len = strlen(mod);
	size_t cap = len * 2 + 32;
	char *guard = arena_alloc(h->ir->arena, cap);
	size_t at = (size_t)snprintf(guard, cap, "R2_");

	for (size_t i = 0; i < len; i++) {
		unsigned char c = (unsigned char)mod[i];

		if (!((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')
				|| (c >= '0' && c <= '9') || c == '_'))
			c = '_';
		guard[at++] = (char)(c >= 'a' && c <= 'z' ? c - 'a' + 'A' : c);
	}
	strcpy(guard + at, "_H");
	h->guard = guard;

	char *macro = guard + at + 3;
	memcpy(macro, guard, at);
	macro[at] = '\0';
	strcpy(macro + at, "_HAS_DYNAMIC_INIT");
	h->init_macro = macro;
}

static void make_api_macro (CHeader *h)
{
	h_printf(h,
		"#ifndef R2_API\n"
		"#if defined(_WIN32) || defined(__CYGWIN__)\n"
		"#  if defined(R2_STATIC) || defined(R2_BUILDING)\n"
		"#    define R2_API\n"
		"#  else\n"
		"#    define R2_API __declspec(dllimport)\n"
		"#  endif\n"
		"#elif defined(__GNUC__) || defined(__clang__)\n"
		"#  define R2_API __attribute__((visibility(\"default\")))\n"
		"#else\n"
		"#  define R2_API\n"
		"#endif\n"
		"#endif\n\n");
}

static void make_packing_macro (CHeader *h)
{
	h_printf(h,
		"#ifndef R2_PACKED\n"
		"#if defined(_MSC_VER)\n"
		"#  define R2_PACKED\n"
		"#elif defined(__GNUC__) || defined(__clang__)\n"
		"#  define R2_PACKED __attribute__((packed))\n"
		"#else\n"
		"#  define R2_PACKED\n"
		"#endif\n"
		"#endif\n"
		"#ifndef R2_PACK_PUSH\n"
		"#if defined(_MSC_VER)\n"
		"#  define R2_PACK_PUSH __pragma(pack(push, 1))\n"
		"#else\n"
		"#  define R2_PACK_PUSH\n"
		"#endif\n"
		"#endif\n"
		"#ifndef R2_PACK_POP\n"
		"#if defined(_MSC_VER)\n"
		"#  define R2_PACK_POP __pragma(pack(pop))\n"
		"#else\n"
		"#  define R2_PACK_POP\n"
		"#endif\n"
		"#endif\n\n");
}

static void print_header_meta (CHeader *h)
{
	Sema *s = h->sema;

	h_printf(h, "// depends:");
	for (uint16_t i = 0; i < s->dep_count; i++)
		h_printf(h, "%s%.*s", i ? ", " : " ",
				(int)s->dep_lens[i], s->deps[i]);
	h_printf(h, "\n// total_imports:");
	int first = 1;
	for (uint32_t i = 0; i < s->module_count; i++) {
		ImportModule *m = s->modules + i;

		h_printf(h, "%s%.*s", first ? " " : ", ",
				(int)m->name_len, m->name);
		first = 0;
	}
	h_printf(h, "\n");
}

static void make_prologue (CHeader *h)
{
	h_printf(h, "/* Generated by r2p -- do not edit. */\n");
	h_printf(h, "// source: %s\n// module: %s\n// target: %s\n",
			h->canon, h->ir->mod, h->ir->target);
	print_header_meta(h);
	h_printf(h, "#define %s 0\n\n", h->init_macro);
	h_printf(h, "#ifndef %s\n#define %s\n\n", h->guard, h->guard);
	h_printf(h, "#include <stddef.h>\n#include <stdint.h>\n\n");
	make_api_macro(h);
	make_packing_macro(h);
	h_printf(h, "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
}

static void patch_init_flag (CHeader *h)
{
	char key[256];
	int n = snprintf(key, sizeof(key), "#define %s ", h->init_macro);

	if (n <= 0 || (size_t)n >= sizeof(key)) return;
	size_t klen = (size_t)n;
	char *at = strstr(h->code, key);

	if (!at || (size_t)(at - h->code) + klen >= h->len) return;
	char *digit = at + klen;

	if (*digit != '0' && *digit != '1') return;
	*digit = h->ir->fns[h->ir->init_fn].count > 1 ? '1' : '0';
}

static void init_maps (CHeader *h)
{
	Arena *a = h->ir->arena;

	h->type_total = type_count;
	h->type_names = arena_alloc(a, sizeof(char *) * type_count);
	h->decl_nodes = arena_alloc(a, sizeof(uint16_t) * type_count);
	h->type_used = arena_alloc(a, type_count);
	h->type_done = arena_alloc(a, type_count);
	h->fn_seen = arena_alloc(a, type_count);
	h->fn_types = arena_alloc(a, sizeof(TypeId) * type_count);
	h->slice_seen = arena_alloc(a, type_count);
	h->slice_types = arena_alloc(a, sizeof(TypeId) * type_count);
	memset(h->type_names, 0, sizeof(char *) * type_count);
	memset(h->decl_nodes, 0xFF, sizeof(uint16_t) * type_count);
	memset(h->type_used, 0, type_count);
	memset(h->type_done, 0, type_count);
	memset(h->fn_seen, 0, type_count);
	memset(h->slice_seen, 0, type_count);
}

int header_generate (CHeader *h, IR *ir, Sema *sema, const char *source, const char *dir)
{
	memset(h, 0, sizeof(*h));
	h->ir = ir;
	h->sema = sema;
	h->source = source;
	h->dir = dir;
	if (!has_exports(sema)) return 0;
	if (r2i_build_path(sema, source, dir, ".h", &h->canon, &h->path)) return 1;

	make_guard(h);
	h->init_sym = mangle_init(ir->arena, ir->mod);
	init_maps(h);
	h_collect_all(h);
	h->cap = 1024;
	h->code = malloc(h->cap);
	if (!h->code) {
		fprintf(stderr, "Not enough memory\n");
		exit(1);
	}
	make_prologue(h);
	h_make_types(h);
	h_make_decls(h);
	h->ready = 1;
	return 0;
}

int header_write (CHeader *h)
{
	if (!h->ready) return 0;
	patch_init_flag(h);
	if (r2i_make_dirs(h->dir) || r2i_make_parent(h->path)
			|| r2i_check_owner(h->path, h->canon)) return 1;

	FILE *f = fopen(h->path, "wb");
	if (!f) {
		fprintf(stderr, "Error: could not open '%s' for writing: %s\n",
				h->path, strerror(errno));
		return 1;
	}
	int failed = fwrite(h->code, 1, h->len, f) != h->len;

	if (fclose(f) != 0) failed = 1;
	if (failed) {
		fprintf(stderr, "Error: could not write '%s'\n", h->path);
		remove(h->path);
	}
	return failed;
}

void header_free (CHeader *h)
{
	free(h->code);
	free(h->canon);
	free(h->path);
	memset(h, 0, sizeof(*h));
}
