#include "r2i/internal.h"

#include <errno.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

#define R2I_PATH_MAX 4096

void r2i_printf (R2i *r, const char *fmt, ...)
{
	va_list ap;
	va_list probe;

	va_start(ap, fmt);
	va_copy(probe, ap);
	int need = vsnprintf(NULL, 0, fmt, probe);
	va_end(probe);
	if (need < 0) {
		va_end(ap);
		return;
	}
	if (r->len + (size_t)need + 1 > r->cap) {
		size_t cap = r->cap;

		while (r->len + (size_t)need + 1 > cap) cap <<= 1;
		char *code = realloc(r->code, cap);

		if (!code) {
			fprintf(stderr, "Not enough memory\n");
			exit(1);
		}
		r->code = code;
		r->cap = cap;
	}
	vsnprintf(r->code + r->len, (size_t)need + 1, fmt, ap);
	va_end(ap);
	r->len += (size_t)need;
}

void r2i_indent (R2i *r, int depth)
{
	for (int i = 0; i < depth; i++)
		r2i_printf(r, "\t");
}

static int valid_name (const char *name, size_t len)
{
	if (!len) return 0;
	for (size_t i = 0; i < len; i++) {
		unsigned char c = (unsigned char)name[i];

		if (!((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')
				|| (c >= '0' && c <= '9') || c == '_' || c == '-'))
			return 0;
	}
	return 1;
}

static int module_file_name (R2i *r, const char **name, size_t *len)
{
	if (r->sema->mod_seen) {
		if (!valid_name(r->sema->mod_name, r->sema->mod_len)) {
			fprintf(stderr, "Error: module name '%.*s' may only contain letters, digits, '_' and '-'\n",
					(int)r->sema->mod_len, r->sema->mod_name);
			return 1;
		}
		*name = r->sema->mod_name;
		*len = r->sema->mod_len;
		return 0;
	}

	const char *base = strrchr(r->source, '/');
	size_t base_len = strlen(base ? base + 1 : r->source);
	base = base ? base + 1 : r->source;
	if (base_len <= 3) {
		fprintf(stderr, "Error: source file '%s' has no name before '.r2'\n", r->source);
		return 1;
	}
	*name = base;
	*len = base_len - 3;
	if (!valid_name(*name, *len)) {
		fprintf(stderr, "Error: source name '%s' may only contain letters, digits, '_' and '-' before '.r2'\n",
				base);
		return 1;
	}
	return 0;
}

static int build_path (R2i *r)
{
	char resolved[R2I_PATH_MAX];
	size_t dir_len = strlen(r->dir);

	const char *name;
	size_t len;
	if (module_file_name(r, &name, &len)) return 1;

	if (!realpath(r->source, resolved)) {
		fprintf(stderr, "Error: cannot resolve the path of '%s'\n", r->source);
		return 1;
	}

	r->canon = malloc(strlen(resolved) + 1);
	if (!r->canon) {
		fprintf(stderr, "Not enough memory\n");
		exit(1);
	}
	strcpy(r->canon, resolved);

	const char *slash = dir_len && r->dir[dir_len - 1] == '/' ? "" : "/";
	size_t cap = dir_len + strlen(slash) + len + 5;

	r->path = malloc(cap);
	if (!r->path) {
		fprintf(stderr, "Not enough memory\n");
		exit(1);
	}
	snprintf(r->path, cap, "%s%s%.*s.r2i", r->dir, slash, (int)len, name);
	return 0;
}

static int make_dirs (const char *dir)
{
	char path[R2I_PATH_MAX];
	size_t len = strlen(dir);

	if (!len || len >= sizeof path) {
		fprintf(stderr, "Error: invalid modules directory '%s'\n", dir);
		return 1;
	}
	memcpy(path, dir, len + 1);
	for (size_t i = 1; i <= len; i++) {
		if (path[i] != '/' && path[i] != '\0') continue;
		char saved = path[i];

		path[i] = '\0';
		if (mkdir(path, 0755) != 0 && errno != EEXIST) {
			fprintf(stderr, "Error: could not create directory '%s': %s\n",
					path, strerror(errno));
			return 1;
		}
		path[i] = saved;
	}
	return 0;
}

static int check_owner (R2i *r)
{
	FILE *f = fopen(r->path, "rb");
	char line[R2I_PATH_MAX + 32];
	char *source = NULL;

	if (!f) {
		if (errno == ENOENT) return 0;
		fprintf(stderr, "Error: could not read '%s': %s\n", r->path, strerror(errno));
		return 1;
	}
	for (int i = 0; i < 16 && fgets(line, sizeof line, f); i++) {
		if (strncmp(line, "// source: ", 11) != 0) {
			if (line[0] != '/') break;
			continue;
		}
		source = line + 11;
		break;
	}
	int failed = 0;

	if (!source) {
		fprintf(stderr, "Error: refusing to overwrite '%s': not generated by r2p\n", r->path);
		failed = 1;
	} else {
		size_t n = strlen(source);

		while (n && (source[n - 1] == '\n' || source[n - 1] == '\r'))
			source[--n] = '\0';
		if (strcmp(source, r->canon) != 0) {
			fprintf(stderr, "Error: refusing to overwrite '%s': it was generated from '%s'\n",
					r->path, source);
			failed = 1;
		}
	}
	fclose(f);
	return failed;
}

int r2i_write (R2i *r)
{
	if (!r->ready) return 0;
	if (make_dirs(r->dir) || check_owner(r)) return 1;

	FILE *f = fopen(r->path, "wb");
	if (!f) {
		fprintf(stderr, "Error: could not open '%s' for writing: %s\n",
				r->path, strerror(errno));
		return 1;
	}
	int failed = fwrite(r->code, 1, r->len, f) != r->len;

	if (fclose(f) != 0) failed = 1;
	if (failed) {
		fprintf(stderr, "Error: could not write '%s'\n", r->path);
		remove(r->path);
	}
	return failed;
}

static int has_init (IR *ir)
{
	IRFn *fn = ir->fns + ir->init_fn;

	for (uint32_t i = 0; i < fn->count; i++) {
		uint8_t op = ir->instrs[fn->start + i].op;

		if (op != IR_NOP && op != IR_RET) return 1;
	}
	return 0;
}

int r2i_generate (R2i *r, IR *ir, Sema *sema, const char *source, const char *dir)
{
	memset(r, 0, sizeof *r);
	r->ir = ir;
	r->sema = sema;
	r->source = source;
	r->dir = dir;

	if (build_path(r)) return 1;
	r2i_build_types(r);
	r->cap = 1024;
	r->code = malloc(r->cap);
	if (!r->code) {
		fprintf(stderr, "Not enough memory\n");
		exit(1);
	}
	r2i_printf(r, "// r2i v1\n// source: %s\n// module: %s\n// has_dynamic_init: %d\n// imports:\n\n",
			r->canon, ir->mod, has_init(ir));
	r2i_make_decls(r);
	r2i_make_init(r);
	r->ready = 1;
	return 0;
}

void r2i_free (R2i *r)
{
	free(r->code);
	free(r->canon);
	free(r->path);
	memset(r, 0, sizeof *r);
}
